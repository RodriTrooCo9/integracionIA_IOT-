            "def simular_onoff(K, tau, theta, SP=20.0, T0=8.5, histeresis=0.5, t_sim=2400.0, dt=1.0):\n",
            "    n = int(t_sim / dt)\n",
            "    t = np.arange(n) * dt\n",
            "    buffer_u = [0.0] * max(1, int(round(theta/dt)))\n",
            "    y = np.zeros(n)\n",
            "    u = np.zeros(n)\n",
            "    e_arr = np.zeros(n)\n",

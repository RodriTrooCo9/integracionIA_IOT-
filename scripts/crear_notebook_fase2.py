            "## 3. Sintonización Clásica de Ganancias PID\n",
            "\n",
            "Calculamos las ganancias con tres metodologías de referencia en control de procesos:\n",
            "\n",
            "| Método | $K_p$ | $T_i$ | $T_d$ |\n",
            "| :--- | :---: | :---: | :---: |\n",

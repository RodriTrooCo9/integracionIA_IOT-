            "    for i in range(1, n):\n",
            "        e_arr[i] = SP - y[i-1]\n",
            "        if y[i-1] < (SP - histeresis) and estado == 0.0:\n",
            "            estado = 100.0\n",
            "            conmutaciones += 1\n",
            "        elif y[i-1] > (SP + histeresis) and estado == 100.0:\n",
